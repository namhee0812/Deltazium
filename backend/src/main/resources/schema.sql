-- 메타데이터: DB 연결 저장소. PG(런타임)·H2 PostgreSQL 모드(테스트) 공용 문법만 사용.
-- CDC 등록 테이블 (마일스톤 4). PK 존재·supp.log ALL은 등록 시점에 검증 완료된 상태로 저장된다.
CREATE TABLE IF NOT EXISTS registered_tables (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schema_name          VARCHAR(128) NOT NULL,
    table_name           VARCHAR(128) NOT NULL,
    source_connection_id BIGINT       NOT NULL,
    target_connection_id BIGINT       NOT NULL,
    created_at           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (schema_name, table_name)
);
-- 타깃 스키마·테이블명이 소스와 다를 수 있다 (NULL = 소스와 동일)
ALTER TABLE registered_tables ADD COLUMN IF NOT EXISTS target_schema_name VARCHAR(128);
ALTER TABLE registered_tables ADD COLUMN IF NOT EXISTS target_table_name  VARCHAR(128);
-- 스냅샷 모드: INITIAL(초기적재 포함) | NO_DATA(현재 시점부터 변경만).
-- snapshot.mode는 커넥터 전역이라 실제 적용은 첫 등록(커넥터 생성) 시점 값이다.
ALTER TABLE registered_tables ADD COLUMN IF NOT EXISTS snapshot_mode VARCHAR(16) DEFAULT 'INITIAL';

-- 컬럼 매핑: 타깃 컬럼 ← source_expr('${소스컬럼}' 형식, 추후 함수·치환 확장 예정).
-- enabled=false면 CDC 적재에서 제외. 실반영: 동일명 매핑은 field.include.list, 리네임은 저장만(스톡 sink 한계).
CREATE TABLE IF NOT EXISTS registered_columns (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registered_table_id BIGINT       NOT NULL,
    target_column       VARCHAR(128) NOT NULL,
    source_expr         VARCHAR(256) NOT NULL,
    enabled             BOOLEAN      NOT NULL DEFAULT TRUE,
    UNIQUE (registered_table_id, target_column)
);

-- 테이블별 운영 이벤트 이력 (라이프사이클·DDL·복구·커넥터 장애 전이).
-- UI 드릴다운 타임라인의 원천 — 원시 로그 통합 대신 구조화된 사건만 적재한다.
CREATE TABLE IF NOT EXISTS table_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    schema_name  VARCHAR(128) NOT NULL,
    table_name   VARCHAR(128) NOT NULL,
    event_type   VARCHAR(32)  NOT NULL,  -- REGISTERED|SUPPLOG_APPLIED|PAUSED|RESUMED|UNREGISTERED|
                                         -- DDL_DETECTED|DDL_APPROVED|DDL_REJECTED|
                                         -- RECOVERY_STARTED|RECOVERY_DONE|RECOVERY_FAILED|
                                         -- CONNECTOR_FAILED|CONNECTOR_RECOVERED
    severity     VARCHAR(8)   NOT NULL,  -- INFO | WARN | ERROR
    message      VARCHAR(1000) NOT NULL,
    detail       VARCHAR(100000)         -- trace 원문 등 (펼침 표시용)
);

-- schema change topic에서 소비한 DDL 이벤트 (7절 승인 워크플로).
-- 토픽 retention(24h) 만료 전에 backend poller가 적재해두는 것이 원본 보존 수단이다.
CREATE TABLE IF NOT EXISTS ddl_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kafka_offset BIGINT       NOT NULL UNIQUE,
    event_ts_ms  BIGINT       NOT NULL,
    scn          VARCHAR(40),
    schema_name  VARCHAR(128),
    table_name   VARCHAR(128),
    ddl_text     VARCHAR(100000) NOT NULL,
    state        VARCHAR(16)  NOT NULL,  -- SNAPSHOT | DETECTED | APPROVED | REJECTED
    note         VARCHAR(1000),
    decided_at   TIMESTAMP
);

CREATE TABLE IF NOT EXISTS db_connections (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL UNIQUE,
    db_type       VARCHAR(20)  NOT NULL DEFAULT 'ORACLE',
    role          VARCHAR(10)  NOT NULL,  -- SOURCE|TARGET (검증은 DbConnectionService — H2 테스트 호환 위해 DB CHECK 미사용)
    host          VARCHAR(255) NOT NULL,
    port          INT          NOT NULL,
    database_name VARCHAR(100) NOT NULL,
    username      VARCHAR(100) NOT NULL,
    password      VARCHAR(255) NOT NULL,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
